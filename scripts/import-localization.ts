import { readFile, writeFile, mkdir } from 'node:fs/promises';
import {createHash} from 'node:crypto';
import { readMo } from './ship-localization.ts';
const input=process.argv[2]??process.env.WOWS_GLOBAL_MO_PATH;
if(!input)throw new Error('Pass the global.mo path or set WOWS_GLOBAL_MO_PATH.');
const buffer=await readFile(input);
const dictionary=readMo(buffer);
if(!Object.keys(dictionary).length)throw new Error('No ship names found; dictionary unchanged.');
const old=JSON.parse(await readFile('data/database/ship-localization.json','utf8')) as Record<string,string>;
const changes=Object.entries(dictionary).filter(([k,v])=>old[k]&&old[k]!==v).map(([key,name])=>({key,previousName:old[key],name}));
const meta={importedAt:new Date().toISOString(),fileName:'global.mo',gameBuild:input.match(/[\\/]bin[\\/](\d+)/)?.[1],sha256:createHash('sha256').update(buffer).digest('hex'),keyCount:Object.keys(dictionary).length};
await mkdir('outputs/localization-review',{recursive:true});
await writeFile('outputs/localization-review/dictionary-diff.json',JSON.stringify({meta,changes,addedKeys:Object.keys(dictionary).filter(k=>!old[k]),removedKeys:Object.keys(old).filter(k=>!dictionary[k])},null,2)+'\n');
await writeFile('data/database/ship-localization.json',JSON.stringify(dictionary,null,2)+'\n');
await writeFile('data/database/ship-localization-meta.json',JSON.stringify(meta,null,2)+'\n');
console.log(`Imported ${Object.keys(dictionary).length} ship localization keys.`);
